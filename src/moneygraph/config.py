"""
Пороги и константы для присвоения ролей, кластеризации и приоритезации.

Все "магические числа" решения живут здесь и нигде больше. Если жюри
спрашивает "почему 8, а не 5" — ответ должен быть в комментарии рядом
с константой, а сама константа должна использоваться в roles.py /
priority.py, а не дублироваться inline.

Пороги ниже откалиброваны на РЕАЛЬНОМ датасете (2248 узлов, 3119 рёбер),
см. распределения в docs/eda_notes.md. Это стартовые значения — команда
может (и должна) их подвинуть по итогам разбора конкретных gid с жюри,
но менять нужно именно тут, а не в логике.
"""

from __future__ import annotations

ROLES = [
    "consolidator",
    "transit",
    "distributor",
    "terminal",
    "coordinator",
    "peripheral",
]

# ---------------------------------------------------------------------------
# CONSOLIDATOR — точка консолидации: получает от нескольких разных плательщиков
# ---------------------------------------------------------------------------
# in_deg на графе: p50=1, p75=1, p90=2, p95=3, p99=6, max=24.
# Организаторы кейса прямо называют диапазон 8-24 как "выраженных кандидатов".
# Берём 3 как мягкий порог (выше p95) и 8 как сильный (высокий role_score).
CONSOLIDATOR_MIN_IN_DEG = 3          # мягкий порог: попадает в кандидаты
CONSOLIDATOR_STRONG_IN_DEG = 8       # сильный порог: высокая уверенность

# ---------------------------------------------------------------------------
# DISTRIBUTOR — веерное распределение на много получателей
# ---------------------------------------------------------------------------
# out_deg (ненулевые): p50=2, p75=3, p90=3, p95=5, p99≈24, max=116.
# Организаторы называют диапазон 60-116 узлов как явных дистрибьюторов.
DISTRIBUTOR_MIN_OUT_DEG = 10         # мягкий порог: попадает в кандидаты
DISTRIBUTOR_STRONG_OUT_DEG = 30      # сильный порог: явное веерное распределение

# ---------------------------------------------------------------------------
# TRANSIT — пропускает деньги дальше, не удерживая
# ---------------------------------------------------------------------------
# pass_through = out_kzt / in_kzt. 72 узла лежат в полосе [0.8, 1.2] —
# "пришло почти столько же, сколько ушло". ВАЖНО: не применяем к seed
# (у seed in_kzt занижен по устройству выгрузки, см. sanity_check).
TRANSIT_PASS_THROUGH_LOW = 0.8
TRANSIT_PASS_THROUGH_HIGH = 1.2
TRANSIT_MIN_IN_KZT = 5_000            # отсекаем шум на копеечных суммах

# Дополнительный временной признак транзита (бонус, требует transactions.parquet):
# деньги пришли и ушли в течение TRANSIT_QUICK_DAYS дней.
TRANSIT_QUICK_DAYS = 2

# ---------------------------------------------------------------------------
# TERMINAL — конечный получатель: деньги приходят и остаются
# ---------------------------------------------------------------------------
# ЛОВУШКА КЕЙСА: out_deg == 0 на depth == 4 не значит "деньги осели" — это
# может быть артефакт обрыва обхода (444 таких узла). Различаем:
#   depth < 4 и out_deg == 0  -> обход этот узел ДОСМОТРЕЛ (искал исходящие
#                                 переводы >= 5000 KZT и не нашёл) => реальный
#                                 терминал, высокая уверенность.
#   depth == 4 и out_deg == 0 -> обход НЕ ДОСМОТРЕЛ дальше этого узла,
#                                 попадание в выборку прервано глубиной =>
#                                 терминал под вопросом, роль присваивается,
#                                 но role_score ниже и evidence явно называет
#                                 причину неопределённости.
TERMINAL_DEPTH4_ROLE_SCORE_CAP = 0.55  # максимум уверенности для depth==4 кейса

# ---------------------------------------------------------------------------
# COORDINATOR — координирующий узел, кандидат в организаторы
# ---------------------------------------------------------------------------
# Финансовый сигнал (высокий in_deg/out_deg) уже покрыт consolidator/distributor.
# Структурный сигнал coordinator: узел, до которого по направленным путям можно
# дойти от НЕСКОЛЬКИХ РАЗНЫХ seed-клиентов (seed_reach >= 2). Это тот самый
# "случайность или структура?" вопрос из starter/README.md.
COORDINATOR_MIN_SEED_REACH = 2
COORDINATOR_STRONG_SEED_REACH = 4

# Betweenness (см. features.py: считается НЕВЗВЕШЕННЫМ, т.к. nx интерпретирует
# weight как "длину" ребра — большая сумма перевода не должна делать путь
# "длиннее"). Топ-квантиль используется как дополнительный сигнал coordinator.
COORDINATOR_BETWEENNESS_QUANTILE = 0.95

# ---------------------------------------------------------------------------
# PRIORITY SCORE — ранжирование для top_nodes.csv
# ---------------------------------------------------------------------------
# Веса ролей: насколько роль сама по себе повышает приоритет проверки.
# consolidator/coordinator — самые ценные с точки зрения AML (организаторы,
# точки сбора денег). distributor — тоже высок (веерная раздача = дробление).
# terminal с truncated_by_depth — отдельно понижаем, т.к. неопределённость выше.
ROLE_PRIORITY_WEIGHT = {
    "coordinator": 1.00,
    "consolidator": 0.90,
    "distributor": 0.75,
    "transit": 0.55,
    "terminal": 0.40,
    "peripheral": 0.10,
}

# ТЗ явно требует сместить фокус с 81 известного "курьера" на новые точки
# консолидации/координации. Поэтому seed-статус НЕ повышает приоритет —
# наоборот, слегка приглушаем его, если по структуре роль всё равно низкая.
SEED_PRIORITY_DAMPING = 0.85

